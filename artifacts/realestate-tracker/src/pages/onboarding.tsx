export default function Onboarding() {
  const { user, isLoaded } = useUser();
  const [, setLocation] = useLocation();

  const [phone, setPhone] = useState("");
  const [phoneError, setPhoneError] = useState("");
  const [termsOpen, setTermsOpen] = useState(false);
  const [termsAccepted, setTermsAccepted] = useState(false);
  const [termsError, setTermsError] = useState("");
  const [saving, setSaving] = useState(false);
  const [saveError, setSaveError] = useState("");

  // Profile fields
  const [howFound, setHowFound] = useState("");
  const [propertyTypes, setPropertyTypes] = useState<string[]>([]);
  const [geoFocus, setGeoFocus] = useState("");

  // If already onboarded, bounce to app (must be before any early returns)
  useEffect(() => {
    if (isLoaded && user?.unsafeMetadata?.onboardingComplete) {
      setLocation("/app");
    }
  }, [isLoaded, user, setLocation]);

  if (!isLoaded) {
    return (
      <div className="flex min-h-dvh items-center justify-center">
        <Loader2 className="w-6 h-6 animate-spin text-muted-foreground" />
      </div>
    );
  }

  if (isLoaded && user?.unsafeMetadata?.onboardingComplete) return null;

  function validatePhone(val: string) {
    const digits = val.replace(/\D/g, "");
    if (digits.length < 10) return "Please enter a valid phone number (at least 10 digits).";
    return "";
  }

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    const pErr = validatePhone(phone);
    setPhoneError(pErr);
    const tErr = termsAccepted ? "" : "You must read and accept the Terms of Service to continue.";
    setTermsError(tErr);
    if (pErr || tErr) return;

    setSaving(true);
    setSaveError("");
    try {
      // 1. Persist acceptance to DB and fire admin notification email
      const primaryEmail =
        user!.primaryEmailAddress?.emailAddress ?? "";
      await fetch("/api/onboarding/complete", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          phone: phone.trim(),
          email: primaryEmail,
          howFound: howFound || null,
          propertyTypes: propertyTypes.length ? propertyTypes.join(",") : null,
          geoFocus: geoFocus.trim() || null,
        }),
      });

      // 2. Store on Clerk user so the gate passes on next load
      await user!.updateMetadata({
        unsafeMetadata: {
          ...((user!.unsafeMetadata as Record<string, unknown>) ?? {}),
          phone: phone.trim(),
          termsAcceptedAt: new Date().toISOString(),
          onboardingComplete: true,
        },
      });
      setLocation("/app");
    } catch {
      setSaveError("Something went wrong saving your profile. Please try again.");
      setSaving(false);
    }
  }

  return (
    <div className="flex min-h-dvh items-center justify-center bg-[hsl(45,20%,97%)] px-4 py-12">
      <div className="w-full max-w-md space-y-6">
        {/* Header */}
        <div className="text-center space-y-2">
          <div className="flex justify-center mb-3">
            <img src="/logo.png" alt="Acreon" className="w-10 h-10" />
          </div>
          <h1 className="text-2xl font-bold text-[hsl(30,20%,15%)]">One last step</h1>
          <p className="text-sm text-[hsl(30,15%,45%)]">
            Before you access Acreon, please provide your phone number and accept our Terms of Service.
          </p>
        </div>

        <form onSubmit={handleSubmit} className="bg-white rounded-xl shadow-lg overflow-hidden">
          <div className="p-6 space-y-5">

            {/* Phone number */}
            <div className="space-y-1.5">
              <label className="text-sm font-medium text-[hsl(30,20%,15%)]">
                Phone Number <span className="text-red-500">*</span>
              </label>
              <div className="relative">
                <Phone className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-muted-foreground pointer-events-none" />
                <Input
                  type="tel"
                  placeholder="(555) 867-5309"
                  value={phone}
                  onChange={e => {
                    setPhone(e.target.value);
                    if (phoneError) setPhoneError(validatePhone(e.target.value));
                  }}
                  className={cn("pl-9", phoneError && "border-red-400 focus-visible:ring-red-400")}
                />
              </div>
              {phoneError && <p className="text-xs text-red-500">{phoneError}</p>}
              <p className="text-xs text-muted-foreground">
                Used for account security and important service notices only.
              </p>
            </div>

            {/* How did you find us */}
            <div className="space-y-1.5">
              <label className="text-sm font-medium text-[hsl(30,20%,15%)]">
                How did you hear about Acreon?
                <span className="ml-1 text-muted-foreground font-normal">(optional)</span>
              </label>
              <div className="grid grid-cols-2 gap-2">
                {HOW_FOUND_OPTIONS.map(opt => (
                  <button
                    key={opt.value}
                    type="button"
                    onClick={() => setHowFound(v => v === opt.value ? "" : opt.value)}
                    className={cn(
                      "px-3 py-2 rounded-lg border text-sm text-left transition-colors",
                      howFound === opt.value
                        ? "border-primary bg-primary/8 text-primary font-medium"
                        : "border-border text-[hsl(30,15%,35%)] hover:border-primary/40 hover:bg-muted/40"
                    )}
                  >
                    {opt.label}
                  </button>
                ))}
              </div>
            </div>

            {/* Property types */}
            <div className="space-y-1.5">
              <label className="text-sm font-medium text-[hsl(30,20%,15%)] flex items-center gap-1.5">
                <Home className="w-3.5 h-3.5 text-muted-foreground" />
                What types of properties do you invest in?
                <span className="ml-1 text-muted-foreground font-normal">(optional)</span>
              </label>
              <div className="grid grid-cols-2 gap-2">
                {PROPERTY_TYPE_OPTIONS.map(opt => {
                  const selected = propertyTypes.includes(opt.value);
                  return (
                    <button
                      key={opt.value}
                      type="button"
                      onClick={() =>
                        setPropertyTypes(prev =>
                          selected ? prev.filter(v => v !== opt.value) : [...prev, opt.value]
                        )
                      }
                      className={cn(
                        "px-3 py-2 rounded-lg border text-sm text-left transition-colors",
                        selected
                          ? "border-primary bg-primary/8 text-primary font-medium"
                          : "border-border text-[hsl(30,15%,35%)] hover:border-primary/40 hover:bg-muted/40"
                      )}
                    >
                      {opt.label}
                    </button>
                  );
                })}
              </div>
            </div>

            {/* Geographic focus */}
            <div className="space-y-1.5">
              <label className="text-sm font-medium text-[hsl(30,20%,15%)] flex items-center gap-1.5">
                <MapPin className="w-3.5 h-3.5 text-muted-foreground" />
                Where do you primarily invest?
                <span className="ml-1 text-muted-foreground font-normal">(optional)</span>
              </label>
              <Input
                type="text"
                placeholder="e.g. Texas, Greater Phoenix, Pacific Northwest"
                value={geoFocus}
                onChange={e => setGeoFocus(e.target.value)}
              />
            </div>

            {/* Terms of Service */}
            <div className="space-y-2">
              <div className="rounded-lg border border-border overflow-hidden">
                {/* Expand/collapse header */}
                <button
                  type="button"
                  onClick={() => setTermsOpen(v => !v)}
                  className="w-full flex items-center justify-between px-4 py-3 bg-muted/40 hover:bg-muted/70 transition-colors text-left"
                >
                  <span className="flex items-center gap-2 text-sm font-medium text-[hsl(30,20%,15%)]">
                    <ShieldCheck className="w-4 h-4 text-primary shrink-0" />
                    Terms of Service &amp; Liability Disclaimer
                  </span>
                  {termsOpen
                    ? <ChevronUp className="w-4 h-4 text-muted-foreground shrink-0" />
                    : <ChevronDown className="w-4 h-4 text-muted-foreground shrink-0" />}
                </button>

                {/* Terms body */}
                {termsOpen && (
                  <div className="px-4 py-3 border-t border-border max-h-64 overflow-y-auto bg-white">
                    <pre className="text-xs text-[hsl(30,15%,35%)] whitespace-pre-wrap leading-relaxed font-sans">
                      {TERMS_TEXT}
                    </pre>
                  </div>
                )}
              </div>

              {/* Acceptance checkbox */}
              <label className="flex items-start gap-3 cursor-pointer select-none group">
                <input
                  type="checkbox"
                  checked={termsAccepted}
                  onChange={e => {
                    setTermsAccepted(e.target.checked);
                    if (e.target.checked) setTermsError("");
                  }}
                  className="mt-0.5 w-4 h-4 accent-primary shrink-0 rounded"
                />
                <span className="text-sm text-[hsl(30,20%,15%)]">
                  I have read and agree to the{" "}
                  <button
                    type="button"
                    onClick={() => setTermsOpen(true)}
                    className="text-primary font-medium underline underline-offset-2 hover:text-primary/80"
                  >
                    Terms of Service &amp; Liability Disclaimer
                  </button>
                  , including the limitation of liability for any financial decisions made using this platform.
                </span>
              </label>
              {termsError && <p className="text-xs text-red-500">{termsError}</p>}
            </div>

            {saveError && (
              <p className="text-sm text-red-500 bg-red-50 rounded-lg px-3 py-2">{saveError}</p>
            )}
          </div>

          {/* Footer */}
          <div className="px-6 py-4 bg-muted/30 border-t border-border">
            <Button
              type="submit"
              disabled={saving}
              className="w-full bg-[hsl(25,85%,45%)] hover:bg-[hsl(25,85%,38%)] text-white font-semibold"
              size="lg"
            >
              {saving
                ? <><Loader2 className="w-4 h-4 mr-2 animate-spin" /> Saving…</>
                : "I Agree and Continue"}
            </Button>
          </div>
        </form>

        <p className="text-center text-xs text-muted-foreground">
          Acreon is for informational purposes only and does not constitute financial advice.
        </p>
      </div>
    </div>
  );
}
